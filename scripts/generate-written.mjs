// Turns scripts/authored/written/*.json into SQL that inserts written-test
// questions (fm_exam_questions) and their mark schemes (fm_mark_schemes).
//
//   node scripts/generate-written.mjs scripts/authored/written/<file>.json [...] > out.sql
//
// Topics and subtopics are looked up by name; a question whose text already
// exists is skipped, so the output is safe to re-run.
import { readFileSync } from 'node:fs'

const lit = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`

function schemeFor(q, shared) {
  if (q.marking_style === 'points' || q.scheme) {
    return { style: q.marking_style || 'points', scheme: q.scheme }
  }
  const levels = q.levels === 'essay' ? shared.essay_levels : shared.paragraph_levels
  const scheme = { levels, indicative: q.indicative }
  if (q.spag_marks) scheme.spag = shared.spag
  if (q.guidance) scheme.guidance = q.guidance
  return { style: 'levels', scheme }
}

export function questionSql(file, q) {
  const { style, scheme } = schemeFor(q, file.shared || {})
  return `with v(qt) as (select ${lit(q.question_text)}::text),
q as (
  insert into public.fm_exam_questions (subtopic_id, topic_id, question_text, command_word, total_marks, difficulty, exam_board, spec_ref, active)
  select st.id, t.id, v.qt, ${lit(q.command_word)}, ${q.total_marks}, ${lit(q.difficulty)}, ${lit(file.exam_board)}, ${lit(q.spec_ref)}, true
  from v, public.subtopics st
  join public.topics t on t.id = st.topic_id
  join public.subjects s on s.id = t.subject_id
  where s.name = ${lit(file.subject)} and t.name = ${lit(q.topic)} and st.name = ${lit(q.subtopic)}
    and not exists (select 1 from public.fm_exam_questions e where e.question_text = v.qt)
  returning id
)
insert into public.fm_mark_schemes (question_id, marking_style, scheme, ao_marks, spag_marks)
select id, ${lit(style)}, ${json(scheme)}, ${json(q.ao_marks || {})}, ${q.spag_marks || 0} from q;
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = ['-- Generated by scripts/generate-written.mjs', 'begin;']
  for (const path of process.argv.slice(2)) {
    const file = JSON.parse(readFileSync(path, 'utf8'))
    out.push(`-- ${file.subject} (${file.exam_board}): ${file.questions.length} questions`)
    for (const q of file.questions) out.push(questionSql(file, q))
  }
  out.push('commit;')
  console.log(out.join('\n'))
}
