// One short quiz per Physics subtopic (AQA 8463), made from the subtopic's
// existing active questions plus the new ones in
// scripts/authored/aqa-8463-physics-subtopic-quizzes.json (keyed by subtopic
// name), so every quiz has at least 8 questions.
//
//   node scripts/authoring/build-physics-subtopic-quizzes.mjs > supabase/content-batches/<date>-physics-subtopic-quizzes.sql
//
// Quizzes are titled "<subtopic> quiz", sit after the topic's existing
// "Quiz N" quizzes, and use the same 168h cooldown. New questions are deduped
// against the whole questions table by normalised text; a quiz that already
// exists is left alone, so the file is safe to re-run.
import { readFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { join } from 'node:path'
import { toRow, balanceLetters, isWellFormed, sqlString } from '../generate-subject.mjs'
import { checkQuestion } from '../../supabase/functions/rewrite-distractors/option-quality.js'

const ROOT = join(import.meta.dirname, '..', '..')
const authored = JSON.parse(readFileSync(join(ROOT, 'scripts/authored/aqa-8463-physics-subtopic-quizzes.json'), 'utf8'))
const spec = JSON.parse(readFileSync(join(ROOT, 'scripts/specs/aqa-8463-physics.json'), 'utf8'))
const HASH_SQL = (col) => `encode(sha256(convert_to(lower(btrim(regexp_replace(${col}, '\\s+', ' ', 'g'))), 'UTF8')), 'hex')`
const batch = process.argv[2] || randomUUID()

const subtopicOrder = new Map()
spec.topics.forEach((t) => t.subtopics.forEach((s, i) => subtopicOrder.set(s.name, { topic: t.name, order: i + 1 })))

const rows = []
for (const [sub, qs] of Object.entries(authored)) {
  if (!subtopicOrder.has(sub)) throw new Error(`unknown subtopic: ${sub}`)
  for (const q of qs) {
    if (!isWellFormed(q)) throw new Error(`badly formed question: ${q.question}`)
    rows.push({ sub, ...toRow(q) })
  }
}
balanceLetters(rows)

const flagged = rows.map((r) => ({ r, c: checkQuestion({ A: r.option_a, B: r.option_b, C: r.option_c, D: r.option_d }, r.correct_option) })).filter(({ c }) => !c.ok)
const longest = rows.filter((r) => checkQuestion({ A: r.option_a, B: r.option_b, C: r.option_c, D: r.option_d }, r.correct_option).correctIsLongest).length
console.error(`${rows.length} new questions, batch ${batch}; correct option longest in ${longest}; ${flagged.length} flagged by option-quality`)
for (const { r, c } of flagged) console.error(`  - ${r.question_text.slice(0, 70)}: ${c.issues.join('; ')}`)

const out = ['-- Generated by scripts/authoring/build-physics-subtopic-quizzes.mjs', `-- batch ${batch}`, 'begin;']
const values = rows.map((r, i) => `  (${i + 1}, ${[r.sub, r.question_text, r.option_a, r.option_b, r.option_c, r.option_d, r.correct_option, r.explanation, r.difficulty, r.question_type, r.ao_weighting].map(sqlString).join(', ')})`)
out.push(`insert into questions (topic_id, subtopic_id, question_text, option_a, option_b, option_c, option_d, correct_option, explanation, difficulty, question_type, ao_weighting, generation_batch_id, content_hash, active, created_at)
select s.topic_id, s.id, v.qt, v.a, v.b, v.c, v.d, v.co, v.ex, v.dif, v.qtype, v.ao, '${batch}', ${HASH_SQL('v.qt')}, true, now() + v.n * interval '1 microsecond'
from (values
${values.join(',\n')}
) as v(n, sub, qt, a, b, c, d, co, ex, dif, qtype, ao)
join subtopics s on s.name = v.sub
join topics t on t.id = s.topic_id
join subjects j on j.id = t.subject_id and j.name = 'Physics'
where not exists (select 1 from questions q where ${HASH_SQL('q.question_text')} = ${HASH_SQL('v.qt')});`)

// One quiz per subtopic in the authored file.
const subs = Object.keys(authored).map((name) => ({ name, ...subtopicOrder.get(name) }))
const subValues = subs.map((s) => `  (${sqlString(s.name)}, ${sqlString(`${s.name} quiz`)}, ${10 + s.order})`).join(',\n')
out.push(`
create temporary table new_subtopic_quizzes (quiz_id uuid, subtopic_id uuid) on commit drop;
with v(sub, title, ord) as (values
${subValues}
), ins as (
  insert into quizzes (topic_id, title, display_order, question_count, cooldown_hours)
  select t.id, v.title, v.ord, 0, 168
  from v
  join subtopics s on s.name = v.sub
  join topics t on t.id = s.topic_id
  join subjects j on j.id = t.subject_id and j.name = 'Physics'
  where not exists (select 1 from quizzes z where z.topic_id = t.id and z.title = v.title)
  returning id, topic_id, title
)
insert into new_subtopic_quizzes (quiz_id, subtopic_id)
select ins.id, s.id from ins join v on v.title = ins.title join subtopics s on s.topic_id = ins.topic_id and s.name = v.sub;

-- Every active question in the subtopic, oldest first.
insert into quiz_questions (quiz_id, question_id, position)
select n.quiz_id, q.id, row_number() over (partition by n.quiz_id order by q.created_at, q.id)
from new_subtopic_quizzes n join questions q on q.subtopic_id = n.subtopic_id and q.active;

update quizzes z set question_count = (select count(*) from quiz_questions qq join questions q on q.id = qq.question_id where qq.quiz_id = z.id and q.active)
where z.id in (select quiz_id from new_subtopic_quizzes);`)
out.push('commit;')
console.log(out.join('\n'))
